# CHUNKING — 1024 chars + 256 overlap
# ============================================================
def chunk_blocos(blocos: list) -> list:
    """Chunkeia blocos preservando número de página de origem.
    Converte tabelas markdown para texto descritivo antes de chunkar."""
    CHUNK_SIZE = 1024
    OVERLAP    = 256

    # ── Pré-processar: converter tabelas para texto
    blocos = converter_tabelas_em_blocos(blocos)

    texto_completo = ""
    mapa_paginas   = []

    for bloco in blocos:
        linha = bloco["texto"]
        if not linha.replace("-","").replace("|","").replace(" ","").strip():
            continue
        inicio_bloco = len(texto_completo)
        texto_completo += linha + "\n"
        mapa_paginas.append((inicio_bloco, len(texto_completo), bloco["pagina"]))

    def pagina_do_chunk(ini_chunk, fim_chunk):
        paginas = []
        for (ini, fim, pag) in mapa_paginas:
            if pag and ini < fim_chunk and fim > ini_chunk:
                sobreposicao = min(fim, fim_chunk) - max(ini, ini_chunk)
                paginas.append((sobreposicao, pag))
        return max(paginas, key=lambda x: x[0])[1] if paginas else None

    chunks = []
    inicio = 0

    while inicio < len(texto_completo):
        fim = inicio + CHUNK_SIZE
        if fim < len(texto_completo):
            quebra = texto_completo.rfind(" ", inicio, fim)
            if quebra == -1:
                quebra = texto_completo.rfind("\n", inicio, fim)
            if quebra != -1:
                fim = quebra

        chunk_texto = texto_completo[inicio:fim].strip()
        if chunk_texto:
            chunks.append({
                "texto":     chunk_texto,
                "pagina_pdf": pagina_do_chunk(inicio, fim)
            })

        inicio = fim - OVERLAP
        if inicio <= 0:
            break

    return chunks

