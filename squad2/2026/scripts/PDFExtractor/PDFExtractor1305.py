def _eh_linha_tabela(texto: str) -> bool:
    """Verifica se uma linha é parte de uma tabela markdown."""
    t = texto.strip()
    return t.startswith("|") and t.endswith("|") and t.count("|") >= 3

def _eh_separador_tabela(texto: str) -> bool:
    """Verifica se é linha separadora (|---|---|)."""
    t = texto.strip().replace("|", "").replace("-", "").replace(":", "").replace(" ", "")
    return len(t) == 0

def tabela_md_para_texto(linhas_tabela: list) -> str:
    """
    Converte linhas de tabela markdown para texto descritivo.

    Entrada:
      ['| Tratamento | N (kg/ha) | Prod (t/ha) |',
       '|---|---|---|',
       '| T1 | 0 | 18.2 |',
       '| T2 | 50 | 22.5 |']

    Saída:
      'Tabela com colunas: Tratamento, N (kg/ha), Prod (t/ha).
       Tratamento T1: N (kg/ha) = 0; Prod (t/ha) = 18.2.
       Tratamento T2: N (kg/ha) = 50; Prod (t/ha) = 22.5.'
    """
    # Parsear cabeçalho e linhas de dados
    headers = []
    rows = []

    for linha in linhas_tabela:
        linha = linha.strip()
        if not linha.startswith("|"):
            continue

        celulas = [c.strip() for c in linha.split("|")[1:-1]]

        if _eh_separador_tabela(linha):
            continue
        elif not headers:
            headers = celulas
        else:
            rows.append(celulas)

    if not headers:
        # Não conseguiu parsear → retorna concatenação simples
        return " ".join(linhas_tabela)

    # ── Montar texto descritivo
    partes = []
    partes.append(f"Tabela com colunas: {', '.join(headers)}.")

    for row in rows:
        # Alinhar com headers (preencher se faltam colunas)
        while len(row) < len(headers):
            row.append("")

        if len(headers) >= 2:
            # Primeira coluna como identificador, restante como valores
            identificador = row[0]
            valores = [f"{headers[i]} = {row[i]}" for i in range(1, len(headers)) if row[i]]
            if identificador and valores:
                partes.append(f"{headers[0]} {identificador}: {'; '.join(valores)}.")
            elif valores:
                partes.append(f"{'; '.join(valores)}.")
        else:
            partes.append(f"{headers[0]}: {row[0]}.")

    return " ".join(partes)


def converter_tabelas_em_blocos(blocos: list) -> list:
    """
    Pré-processa a lista de blocos: encontra sequências de linhas
    de tabela markdown e DUPLICA — mantém o original em markdown
    E adiciona uma versão em texto descritivo logo depois.

    Isso permite busca tanto por valores exatos (markdown)
    quanto por semântica (texto descritivo).
    """
    resultado = []
    buffer_tabela = []   # acumula linhas de tabela consecutivas
    pagina_tabela = None

    def flush_tabela():
        nonlocal buffer_tabela, pagina_tabela
        if buffer_tabela:
            # 1) Manter original em markdown
            resultado.append({
                "texto": "\n".join(buffer_tabela),
                "pagina": pagina_tabela
            })
            # 2) Adicionar versão em texto descritivo
            texto_convertido = tabela_md_para_texto(buffer_tabela)
            resultado.append({
                "texto": texto_convertido,
                "pagina": pagina_tabela
            })
            buffer_tabela = []
            pagina_tabela = None

    for bloco in blocos:
        texto = bloco["texto"]
        pagina = bloco["pagina"]

        # Verificar se TODAS as linhas deste bloco são tabela
        linhas = texto.strip().splitlines()
        linhas_tabela = [l for l in linhas if _eh_linha_tabela(l) or _eh_separador_tabela(l)]

        if len(linhas_tabela) == len(linhas) and len(linhas) > 0:
            # Bloco inteiro é tabela → acumula
            buffer_tabela.extend(linhas)
            if pagina_tabela is None:
                pagina_tabela = pagina
        else:
            # Bloco normal → flush tabela acumulada, depois adiciona bloco
            flush_tabela()
            resultado.append(bloco)

    # Flush final
    flush_tabela()

    return resultado


