# EXTRAÇÃO DE IMAGENS — página inteira + filtro OpenCV
#   1) Docling identifica páginas candidatas (PictureItem)
#   2) Coleta contexto textual anterior de cada imagem
#   3) Renderiza a página via PyMuPDF
#   4) OpenCV analisa se a página TEM conteúdo visual real
#      (descarta páginas só-texto que o Docling marcou errado)
# ============================================================

def pagina_tem_figura(img_path: str) -> bool:
    """
    Analisa a imagem renderizada de uma página e decide se ela
    contém figuras reais (gráficos, fotos, diagramas) ou é só texto.

    3 camadas de detecção:
      1) COR: figuras científicas quase sempre têm elementos coloridos
         (linhas, barras, áreas). Texto e logos são preto/cinza.
      2) DENSIDADE: dentro de cada blob grande, texto é esparso (~5-12%
         de pixels preenchidos), figuras são densas (>15%).
      3) DIREÇÃO DE BORDAS: texto tem bordas predominantemente horizontais
         (linhas de base das letras). Figuras têm bordas em todas direções.
    """
    img = cv2.imread(img_path)
    if img is None:
        return False

    h, w = img.shape[:2]
    area_pagina = h * w

    # ══════════════════════════════════════════════
    # CAMADA 1: DETECÇÃO DE COR
    # ══════════════════════════════════════════════
    # Gráficos de linhas, barras, pizza → linhas/áreas coloridas
    # Texto, logos P&B, caixas de texto → sem saturação
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
    # Pixels com saturação significativa, não muito escuros nem claros
    mascara_cor = (hsv[:, :, 1] > 40) & (hsv[:, :, 2] > 50) & (hsv[:, :, 2] < 240)
    pct_colorido = np.sum(mascara_cor) / area_pagina

    if pct_colorido > 0.015:  # >1.5% da página com cor → tem figura
        return True

    # ══════════════════════════════════════════════
    # CAMADA 2: ANÁLISE DE BLOCOS (para figuras P&B)
    # ══════════════════════════════════════════════
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    _, binary = cv2.threshold(gray, 230, 255, cv2.THRESH_BINARY_INV)

    # Dilatação moderada para fundir elementos de uma mesma figura
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (25, 25))
    dilatada = cv2.dilate(binary, kernel, iterations=1)

    contornos, _ = cv2.findContours(dilatada, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    for cnt in contornos:
        x, y, bw, bh = cv2.boundingRect(cnt)
        blob_area_ratio = (bw * bh) / area_pagina

        # Ignorar blobs pequenos (< 3% da página)
        if blob_area_ratio < 0.03:
            continue

        # ── Analisar conteúdo DENTRO do blob (imagem original binarizada)
        roi = binary[y:y+bh, x:x+bw]
        pixels_preenchidos = np.sum(roi > 0)
        fill_density = pixels_preenchidos / (bw * bh)

        # Texto em caixa/quadro: letras pequenas com espaço entre linhas
        #   → fill density baixa (~5-12%)
        # Logo pequeno dentro de área grande: também baixa density
        # Gráfico P&B: linhas grossas, eixos, pontos, barras
        #   → fill density média-alta (>15%)
        # Foto: fill density alta (>40%)
        if fill_density < 0.13:
            continue  # Esparso demais → texto ou caixa vazia

        # ── CAMADA 3: DIREÇÃO DAS BORDAS
        # Texto = bordas predominantemente horizontais (baselines das letras)
        # Figuras = bordas em múltiplas direções (eixos, linhas, curvas)
        sobel_h = cv2.Sobel(roi, cv2.CV_64F, 0, 1, ksize=3)  # bordas horizontais
        sobel_v = cv2.Sobel(roi, cv2.CV_64F, 1, 0, ksize=3)  # bordas verticais
        energia_h = np.sum(np.abs(sobel_h))
        energia_v = np.sum(np.abs(sobel_v))

        if energia_v > 0:
            ratio_hv = energia_h / energia_v
        else:
            ratio_hv = 999

        # Texto puro: ratio_hv > 2.0 (muito mais bordas horizontais)
        # Figuras: ratio_hv < 2.0 (bordas distribuídas)
        if ratio_hv > 2.0:
            continue  # Dominado por bordas horizontais → texto

        # Passou em density E em direção de bordas → é figura
        return True

    return False


def extrair_paginas_com_imagens(pdf_bytes, docling_doc, filename, img_dir, dpi=150):
    """
    1) Itera elementos do Docling na ordem de leitura
    2) Detecta PictureItem (figuras/gráficos/fotos) — NÃO tabelas
       (tabelas são convertidas para texto descritivo no chunking)
    3) Acumula texto → guarda contexto anterior
    4) Renderiza página inteira via PyMuPDF
    5) OpenCV valida se a página tem conteúdo visual real

    Retorna lista de dicts com info de cada página salva + contexto textual.
    """
    # ── Passo 1: iterar elementos, coletar páginas candidatas + contexto
    texto_acumulado = ""
    # page_no → {"n_imgs": int, "contextos": [str, ...]}
    paginas_candidatas = {}

    for element, _level in docling_doc.iterate_items():
        # Se for texto, acumula
        texto = getattr(element, "text", None)
        if texto and texto.strip():
            texto_acumulado += texto.strip() + "\n"
            continue

        # Se não for PictureItem, pula
        if not isinstance(element, PictureItem):
            continue

        # Extrair página
        page_no = None
        if hasattr(element, "prov") and element.prov:
            page_no = element.prov[0].page_no
        if page_no is None:
            continue

        # Registrar página candidata + contexto textual anterior (últimos 800 chars)
        contexto = texto_acumulado[-800:].strip() if texto_acumulado else ""
        if page_no not in paginas_candidatas:
            paginas_candidatas[page_no] = {"n_imgs": 0, "contextos": []}
        paginas_candidatas[page_no]["n_imgs"] += 1
        paginas_candidatas[page_no]["contextos"].append(contexto)

    if not paginas_candidatas:
        return []

    print(f"    📍 Páginas candidatas (Docling): {dict((k, v['n_imgs']) for k, v in sorted(paginas_candidatas.items()))}")

    # ── Passo 2: renderizar cada candidata e filtrar com OpenCV
    pdf_doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    stem = Path(filename).stem
    paginas_salvas = []
    pags_descartadas = 0

    for page_no in sorted(paginas_candidatas.keys()):
        page_idx = page_no - 1
        if page_idx < 0 or page_idx >= len(pdf_doc):
            continue

        img_filename = f"{stem}-pagina-{page_no:03d}.png"
        img_path = img_dir / img_filename

        try:
            # Renderizar
            page = pdf_doc[page_idx]
            mat = fitz.Matrix(dpi / 72.0, dpi / 72.0)
            pix = page.get_pixmap(matrix=mat)
            pix.save(str(img_path))
            larg, alt = pix.width, pix.height
            del pix
            gc.collect()

            # ── FILTRO OPENCV: página tem figura real?
            if not pagina_tem_figura(str(img_path)):
                os.remove(str(img_path))
                pags_descartadas += 1
                continue

            info = paginas_candidatas[page_no]
            n_imgs = info["n_imgs"]
            melhor_contexto = max(info["contextos"], key=len) if info["contextos"] else ""

            print(f"    ✅ p.{page_no} ({n_imgs} img) → {img_filename} ({larg}x{alt}px) ctx={len(melhor_contexto)}ch")

            paginas_salvas.append({
                "arquivo_imagem":    img_filename,
                "caminho":           str(img_path),
                "pagina_pdf":        page_no,
                "imagens_na_pagina": n_imgs,
                "largura_px":        larg,
                "altura_px":         alt,
                "dpi":               dpi,
                "contexto_textual":  melhor_contexto,
                "gemini_processado": False,
            })

        except Exception as e:
            print(f"    ❌ Falha p.{page_no}: {e}")

    pdf_doc.close()

    if pags_descartadas > 0:
        print(f"    🚫 {pags_descartadas} páginas descartadas (só texto/logos)")

    return paginas_salvas


