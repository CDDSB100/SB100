def converter_pdf_bytes(pdf_bytes: bytes):
    """
    Retorna (blocos, docling_document).
    blocos = lista de {texto, pagina}.
    docling_document = objeto DoclingDocument (necessário para detectar imagens).
    Se falhar: (None, None).
    """
    pipeline_options = PdfPipelineOptions()
    pipeline_options.do_ocr = True
    pipeline_options.do_table_structure = True
    pipeline_options.table_structure_options.do_cell_matching = True
    pipeline_options.ocr_options = TesseractCliOcrOptions(
        lang=["por", "eng", "spa"], force_full_page_ocr=True
    )
    pipeline_options.generate_picture_images = True

    converter = DocumentConverter(
        format_options={InputFormat.PDF: PdfFormatOption(pipeline_options=pipeline_options)}
    )
    with tempfile.NamedTemporaryFile(suffix=".pdf", delete=False) as tmp:
        tmp.write(pdf_bytes)
        tmp_path = tmp.name
    try:
        doc = converter.convert(tmp_path).document
        blocos = []
        for element, _ in doc.iterate_items():
            texto = getattr(element, "text", None)
            if not texto or not texto.strip():
                continue
            page_no = None
            if hasattr(element, "prov") and element.prov:
                page_no = element.prov[0].page_no
            blocos.append({"texto": texto.strip(), "pagina": page_no})
        return (blocos, doc) if blocos else (None, None)
    except Exception as e:
        print(f"  ⚠️  Modo completo falhou ({e}). Tentando modo simples...")
        try:
            simple = PdfPipelineOptions()
            simple.do_ocr = False
            simple.do_table_structure = False
            doc = DocumentConverter(
                format_options={InputFormat.PDF: PdfFormatOption(pipeline_options=simple)}
            ).convert(tmp_path).document
            blocos = []
            for element, _ in doc.iterate_items():
                texto = getattr(element, "text", None)
                if not texto or not texto.strip():
                    continue
                page_no = None
                if hasattr(element, "prov") and element.prov:
                    page_no = element.prov[0].page_no
                blocos.append({"texto": texto.strip(), "pagina": page_no})
            return (blocos, doc) if blocos else (None, None)
        except Exception as e2:
            print(f"  ❌ Falha total: {e2}")
            return (None, None)
    finally:
        try:
            os.remove(tmp_path)
        except OSError:
            pass

